-- moderation 모듈 — com.echo.moderation.domain.BannedWord / Report
-- 금칙어 목록은 코드가 아니라 이 테이블로 관리한다 (소문자로 정규화해 저장).
CREATE TABLE IF NOT EXISTS banned_words (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    word       VARCHAR(50)  NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_banned_words_word UNIQUE (word)
);

-- 게시물 신고. 상태는 PENDING → REVIEWED → RESOLVED 순서로만 진행한다.
CREATE TABLE IF NOT EXISTS reports (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id BIGINT       NOT NULL,
    post_id     BIGINT       NOT NULL,
    reason      VARCHAR(500) NOT NULL,
    status      VARCHAR(20)  NOT NULL,
    created_at  TIMESTAMP(6) NOT NULL,
    updated_at  TIMESTAMP(6) NOT NULL,
    CONSTRAINT ck_reports_status CHECK (status IN ('PENDING', 'REVIEWED', 'RESOLVED'))
);
